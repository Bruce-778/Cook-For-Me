export function correctIngredients(slug: string, ingredients: Ingredient[]): Ingredient[] {
  const correction = changes[slug];
  if (!correction) return ingredients;
  const removed = new Set([...(correction.remove ?? []), ...(correction.add ?? []).map(i => i.name)]);
  return [...ingredients.filter(i => !removed.has(i.name)), ...(correction.add ?? [])];
}

function s(title: string, text: string, minutes: number, ingredients: string[], cue: string, heat: Heat = "不适用", waterTemperature: WaterTemperature = "不适用", oilTemperature = "不适用", safety?: string): RecipeStep {
  const timerSeconds = Math.round(minutes * 60);
  return { title, text, heat, waterTemperature, oilTemperature, time: timerSeconds < 60 ? `${timerSeconds} 秒` : `${minutes} 分钟`, timerSeconds, ingredients, cue, safety };
}

